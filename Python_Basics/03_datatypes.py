#Python datatypes
#Integer
age=22
print("Age :",age)
print("Datatype :",type(age))

#Float
height=5.2
print("\nHeight :",height)
print("Datatype :",type(height))

#String
name="Parth"
print("\nName :",name)
print("Datatype :",type(name))

#Boolean
is_student =True
print("\n",is_student)
print("Datatype :",type(is_student))

#Complex
num= 3 + 7j
print("\nNumber :",num)
print("Datatype :",type(num))